// 抖音礼物清单里混着一批「道具」：加成卡、暴击卡、助力票、解冻卡、测试占位这些，
// 观众根本送不出来。礼物菜单、礼物触发、礼物图选择器都不该出现它们。
// 主进程和渲染进程共用这一份判断，避免两边名单对不上。
const PROP_KEYWORDS = [
  // 只挡真正的功能道具：这些是平台发的卡片/内部占位，观众送不出来。
  // 注意别误伤票类——人气票、上车票、集结票、戏票都是观众能送的真礼物。
  '加成卡', '暴击卡', '人气卡', '助力卡', '狂欢卡', '迷雾卡', '解冻卡', '借力卡',
  '融合卡', '定身卡', '公告卡', '入团卡', '体验卡', '认证卡', '守护卡', '刺客卡',
  '里程加加卡', '圆梦值加成卡', '测试勿动', '占位', '礼物定制中', '礼物邮箱', '融合礼物（基础）'
]

// 组合装：同一个礼物的打包卖法（1314个小心心、浪漫心愿包100包、玫瑰520…）。
// 触发端按「小心心 ×1314」上报的还是基础礼物名，菜单里留组合装只会重复+误导。
// 「666」是独立真礼物，规则都避开它：数字后必须带「个/包」或数字前必须有名字。
const BUNDLE_PATTERNS = [
  /^\d+个/, // 1314个小心心 / 520个小心心 / 66个小心心
  /\d+包$/, // 浪漫心愿包10包 / 100包 等
  /.+(520|999|1314)$/, // 玫瑰520 / 玫瑰999（要求数字前有名字，不误伤 666）
  /\d+个特效/, // 太南了66个特效（基础礼物「太南了」保留）
  /^定制礼物No/, // 定制礼物No2-10月 这类内部定制占位
  /^新buff/, // 新buff-交互式礼物 / 新buff抖音一号（内部实验命名）
  /^LL$/ // 无意义内部条目
]

export function isRealGift(name: string): boolean {
  const value = String(name || '').trim()
  if (!value) return false
  if (PROP_KEYWORDS.some((keyword) => value.includes(keyword))) return false
  return !BUNDLE_PATTERNS.some((pattern) => pattern.test(value))
}
